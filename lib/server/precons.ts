import "server-only";

import { readFile } from "node:fs/promises";
import path from "node:path";

import { cacheLife } from "next/cache";

import { frontFaceName, nameKey } from "@/lib/cards/names";
import type { Card, CommanderSummary } from "@/lib/cards/types";
import { commandZone } from "@/lib/decks/command-zone";
import { analyzePrecon, type PreconAnalysis } from "@/lib/precons/analysis";
import { preconCardNames, preconDeck, type PreconDeck } from "@/lib/precons/deck";
import { printedBracket } from "@/lib/precons/page-text";
import { identityKey, withSlugs, type SluggedPrecon } from "@/lib/precons/slug";
import type { PreconList, PreconSummary } from "@/lib/precons/types";
import { ARCHETYPE_LABELS, type ArchetypeId } from "@/lib/tagging/archetypes";
import { detectThemes, THEMES } from "@/lib/tagging/themes";

import { findCard, getCardDb, type CardDb } from "./card-db";

// Generated by scripts/build-precons.ts and scripts/build-card-db.ts; any of them may be missing when the
// data scripts failed, which leaves the precon pages empty instead of failing the build.
const DATA_DIR = path.join(process.cwd(), "public/data");
const PRECONS_FILE = path.join(DATA_DIR, "precons.json");
const COMMANDERS_FILE = path.join(DATA_DIR, "commanders.json");

/** Archetype affinity from which a commander counts as playing it (0.6 = Scryfall Tagger, 1 = EDHREC). */
const MIN_AFFINITY = 0.5;
const MAX_THEMES = 3;
const MAX_SAME_COLORS = 4;

/** Rules-text themes that name the same strategy as an archetype under another id, so a page shows it once. */
const THEME_SAME_AS: Partial<Record<string, ArchetypeId>> = {
  sacrifice: "aristocrats",
  combat: "aggro",
  discard: "wheels",
  enchantments: "enchantress",
  control: "stax",
};

export interface PreconTheme {
  id: string;
  label: string;
}

export interface PreconPage {
  summary: SluggedPrecon;
  analysis: PreconAnalysis;
  /** Two or three strategies of the commanders, strongest first. */
  themes: PreconTheme[];
  /** Other precons of the same product, newest first. */
  sameSet: SluggedPrecon[];
  /** Up to four precons of the same color identity from other products, newest first. */
  sameColors: SluggedPrecon[];
}

export interface PreconBracketSummary {
  /** Precons checked: those whose list resolved. */
  total: number;
  /** Precons that break no rule of Core (bracket 2) as printed. Two-card combos were not checked. */
  fitCore: number;
  /** Precons with at least one Game Changer, commanders included. */
  withGameChangers: number;
  combosChecked: false;
  /** The precons with the most Game Changers, most first (up to five). */
  mostGameChangers: (Pick<SluggedPrecon, "slug" | "name" | "set" | "releaseDate"> & { gameChangers: string[] })[];
}

async function readJson<T>(file: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(file, "utf8")) as T;
  } catch {
    return null;
  }
}

/** The card database, or null when data/cards.json is missing. */
async function cardDb(): Promise<CardDb | null> {
  try {
    return await getCardDb();
  } catch {
    return null;
  }
}

/** Every precon of the generated list with its slug, newest first. Slugs never depend on the card database. */
async function allPrecons(): Promise<SluggedPrecon[]> {
  const precons = (await readJson<PreconSummary[]>(PRECONS_FILE)) ?? [];
  const newestFirst = [...precons].sort((a, b) => b.releaseDate.localeCompare(a.releaseDate));
  return withSlugs(newestFirst);
}

async function readList(id: string): Promise<PreconList | null> {
  // Ids are MTGJSON file names such as "VirtueAndValor_WOC"; anything else never reaches the file system.
  if (!/^\w+$/.test(id)) return null;
  return readJson<PreconList>(path.join(DATA_DIR, "precons", `${id}.json`));
}

/** The precon as a deck, with its names resolved against the card database. */
async function resolvePrecon(db: CardDb, id: string): Promise<PreconDeck | null> {
  const list = await readList(id);
  if (!list) return null;
  const cards: Record<string, Card> = {};
  for (const name of preconCardNames(list)) {
    const card = findCard(db, name);
    if (card) cards[name] = card;
  }
  return preconDeck(list, cards);
}

/**
 * Every precon whose commander is in the card database, with its page slug, newest first. Empty when the
 * generated data is missing. Cached for good: the data only changes with a new build.
 */
export async function listPrecons(): Promise<SluggedPrecon[]> {
  "use cache";
  cacheLife("max");

  const db = await cardDb();
  if (!db) return [];
  return (await allPrecons()).filter((p) => p.commanders.length > 0 && findCard(db, p.commanders[0]));
}

/** The listed precon with this slug, or null. */
export async function preconBySlug(slug: string): Promise<SluggedPrecon | null> {
  return (await listPrecons()).find((p) => p.slug === slug) ?? null;
}

let commanderIndex: Promise<Map<string, CommanderSummary>> | null = null;

/** public/data/commanders.json by name key, read once per server instance. */
function commanders(): Promise<Map<string, CommanderSummary>> {
  commanderIndex ??= readJson<CommanderSummary[]>(COMMANDERS_FILE).then((list) => {
    const index = new Map<string, CommanderSummary>();
    for (const commander of list ?? []) {
      index.set(nameKey(commander.name), commander);
      const front = nameKey(frontFaceName(commander.name));
      if (!index.has(front)) index.set(front, commander);
    }
    return index;
  });
  return commanderIndex;
}

/**
 * The strategies of the commanders: archetypes they play strongly (merged for a pair, strongest first),
 * then the themes of their rules text. Commanders missing from commanders.json fall back to their text.
 */
function themesOf(zone: readonly Card[], index: Map<string, CommanderSummary>): PreconTheme[] {
  const affinity = new Map<ArchetypeId, number>();
  const themeIds: string[] = [];
  for (const card of zone) {
    const summary = index.get(nameKey(card.name)) ?? index.get(nameKey(frontFaceName(card.name)));
    if (!summary) {
      themeIds.push(...detectThemes(card.oracleText));
      continue;
    }
    for (const [id, value] of Object.entries(summary.archetypes) as [ArchetypeId, number][]) {
      if (value >= MIN_AFFINITY && value > (affinity.get(id) ?? 0)) affinity.set(id, value);
    }
    themeIds.push(...summary.themes);
  }

  const candidates: (PreconTheme & { sameAs?: string })[] = [
    ...[...affinity]
      .sort(([a, x], [b, y]) => y - x || ARCHETYPE_LABELS[a].localeCompare(ARCHETYPE_LABELS[b]))
      .map(([id]) => ({ id, label: ARCHETYPE_LABELS[id] })),
    ...themeIds.flatMap((id) => {
      const theme = THEMES.find((t) => t.id === id);
      return theme ? [{ id: theme.id, label: theme.label, sameAs: THEME_SAME_AS[theme.id] }] : [];
    }),
  ];
  if (!candidates.length) {
    for (const card of zone) {
      for (const id of detectThemes(card.oracleText)) {
        const theme = THEMES.find((t) => t.id === id);
        if (theme) candidates.push({ id: theme.id, label: theme.label });
      }
    }
  }

  const themes: PreconTheme[] = [];
  const seen = new Set<string>();
  for (const { sameAs, ...theme } of candidates) {
    const label = theme.label.toLowerCase();
    if (seen.has(theme.id) || seen.has(label) || (sameAs && seen.has(sameAs))) continue;
    seen.add(theme.id);
    seen.add(label);
    themes.push(theme);
    if (themes.length === MAX_THEMES) break;
  }
  return themes;
}

/**
 * Everything the page of one precon shows, or null for an unknown slug or a list that does not resolve.
 * Reads only local generated data, so the pages prerender; cached for good.
 */
export async function loadPreconPage(slug: string): Promise<PreconPage | null> {
  "use cache";
  cacheLife("max");

  const precons = await listPrecons();
  const summary = precons.find((p) => p.slug === slug);
  const db = summary && (await cardDb());
  if (!summary || !db) return null;
  const deck = await resolvePrecon(db, summary.id);
  if (!deck) return null;

  const key = identityKey(summary.colorIdentity);
  const sameSet = precons.filter((p) => p.set === summary.set && p.id !== summary.id);
  const sameColors = precons
    .filter((p) => p.set !== summary.set && p.id !== summary.id && identityKey(p.colorIdentity) === key)
    .slice(0, MAX_SAME_COLORS);

  return {
    summary,
    analysis: analyzePrecon(deck),
    themes: themesOf(commandZone(deck), await commanders()),
    sameSet,
    sameColors,
  };
}

/**
 * How many listed precons share each color identity, keyed by sorted WUBRG letters ("" for colorless).
 * Identities without a precon are left out.
 */
export async function preconCountsByIdentity(): Promise<Record<string, number>> {
  "use cache";
  cacheLife("max");

  const counts: Record<string, number> = {};
  for (const precon of await listPrecons()) {
    const key = identityKey(precon.colorIdentity);
    counts[key] = (counts[key] ?? 0) + 1;
  }
  return counts;
}

/** How the precons fare against Core (bracket 2) as printed, without the two-card combo check. */
export async function preconBracketSummary(): Promise<PreconBracketSummary> {
  "use cache";
  cacheLife("max");

  const precons = await listPrecons();
  const db = await cardDb();
  const checked = db
    ? await Promise.all(
        precons.map(async (precon) => {
          const deck = await resolvePrecon(db, precon.id);
          return deck && { precon, analysis: analyzePrecon(deck) };
        }),
      )
    : [];
  const analyzed = checked.filter((entry) => entry !== null);

  return {
    total: analyzed.length,
    fitCore: analyzed.filter(({ analysis }) => printedBracket(analysis).bracket === 2).length,
    withGameChangers: analyzed.filter(({ analysis }) => analysis.gameChangers.length > 0).length,
    combosChecked: false,
    mostGameChangers: analyzed
      .filter(({ analysis }) => analysis.gameChangers.length > 0)
      .sort((a, b) => b.analysis.gameChangers.length - a.analysis.gameChangers.length)
      .slice(0, 5)
      .map(({ precon, analysis }) => ({
        slug: precon.slug,
        name: precon.name,
        set: precon.set,
        releaseDate: precon.releaseDate,
        gameChangers: analysis.gameChangers,
      })),
  };
}
